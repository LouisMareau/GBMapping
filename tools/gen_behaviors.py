"""Writes crates/gbmapping-core/src/behaviors.rs: the metatile behaviors' names, from the
decompilations' include/constants/metatile_behaviors.h (pokeemerald: an enum; pokefirered: defines).

    python tools/gen_behaviors.py <pokeemerald's header> <pokefirered's header>
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates" / "gbmapping-core" / "src" / "behaviors.rs"


def parse(text):
    """{value: name} from an enum's members or from #define lines (the first name of a value wins)."""
    out = {}
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    for name, value in re.findall(r"^#define\s+MB_(\w+)\s+(0x[0-9A-Fa-f]+|\d+)\s*$", text, flags=re.M):
        out.setdefault(int(value, 0), name)
    enum = re.search(r"enum\s*\{(.*?)\}", text, flags=re.S)
    if enum:
        value = 0
        for member in enum.group(1).split(","):
            member = member.strip()
            if not member:
                continue
            name, _, explicit = (part.strip() for part in member.partition("="))
            if explicit:
                value = int(explicit, 0)
            if name.startswith("MB_"):
                out.setdefault(value, name[3:])
            value += 1
    return {v: n for v, n in out.items() if not n.startswith("NUM_") and n != "INVALID" and v < 0x200}


def table(name, names):
    lines = [f"pub static {name}: &[(u16, &str)] = &["]
    lines += [f'    (0x{value:02X}, "{names[value]}"),' for value in sorted(names)]
    lines.append("];")
    return "\n".join(lines)


def main():
    emerald, firered = (parse(Path(p).read_text(encoding="utf-8")) for p in sys.argv[1:3])
    OUT.write_text(
        "//! The metatile behaviors' names (the decompilations' MB_ constants), sorted by value.\n"
        "//! Generated by tools/gen_behaviors.py: don't edit.\n\n"
        + table("EMERALD", emerald) + "\n\n" + table("FIRERED", firered) + "\n",
        encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(emerald)} Emerald behaviors, {len(firered)} FireRed ones")


if __name__ == "__main__":
    main()
