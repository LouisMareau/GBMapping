"""Writes crates/gbmapping-core/src/map_names.rs: the maps' names in the original games, from
the decompilations' data/maps/map_groups.json (pokecrystal: data/maps/maps.asm). A ROM doesn't
hold those names (only its places' names: "PETALBURG CITY" for the city, its gym and its houses
alike).

    python tools/gen_map_names.py <pokeemerald's map_groups.json> <pokefirered's map_groups.json> <pokecrystal's maps.asm>
"""
import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates" / "gbmapping-core" / "src" / "map_names.rs"


def table(name, path):
    groups = json.loads(Path(path).read_text(encoding="utf-8"))
    lines = [f"pub static {name}: &[(&str, &[&str])] = &["]
    count = 0
    for group in groups["group_order"]:
        maps = groups[group]
        count += len(maps)
        lines.append(f'    ("{group.removeprefix("gMapGroup_")}", &[' + ", ".join(f'"{m}"' for m in maps) + "]),")
    lines.append("];")
    print(f"{name}: {count} maps in {len(groups['group_order'])} groups")
    return "\n".join(lines)


def crystal(name, path):
    """pokecrystal's groups: a `MapGroup_Name:` label, then a `map Name, ...` line per map."""
    groups = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if group := re.match(r"MapGroup_(\w+):", line):
            groups.append((group.group(1), []))
        elif groups and (entry := re.match(r"\s+map (\w+),", line)):
            groups[-1][1].append(entry.group(1))
    lines = [f"pub static {name}: &[(&str, &[&str])] = &["]
    lines += [f'    ("{group}", &[' + ", ".join(f'"{m}"' for m in maps) + "])," for group, maps in groups]
    lines.append("];")
    print(f"{name}: {sum(len(maps) for _, maps in groups)} maps in {len(groups)} groups")
    return "\n".join(lines)


def main():
    emerald, firered, crystal_maps = sys.argv[1:4]
    OUT.write_text(
        "//! The maps' names in the original games (the decompilations' names), by group.\n"
        "//! Generated by tools/gen_map_names.py: don't edit.\n\n"
        "#[rustfmt::skip]\n" + table("EMERALD", emerald) + "\n\n#[rustfmt::skip]\n" + table("FIRERED", firered)
        + "\n\n#[rustfmt::skip]\n" + crystal("CRYSTAL", crystal_maps) + "\n",
        encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
