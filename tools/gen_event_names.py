"""Writes crates/gbmapping-core/src/event_names.rs: the names the decompilations give to the
overworld sprites (OBJ_EVENT_GFX_), the movement types (MOVEMENT_TYPE_) and the items (ITEM_),
for Emerald and for FireRed/LeafGreen.

    python tools/gen_event_names.py <pokeemerald's include/constants> <pokefirered's include/constants>

Each folder needs event_objects.h, event_object_movement.h and items.h.
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "crates" / "gbmapping-core" / "src" / "event_names.rs"


def strip(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def evaluate(expression, known):
    """A constant expression of numbers, + - * and names already known; `None` when it's anything else."""
    expression = re.sub(r"\b[A-Z_][A-Z0-9_]*\b", lambda m: str(known[m.group(0)]) if m.group(0) in known else "?", expression)
    if "?" in expression or not re.fullmatch(r"[\s0-9a-fA-FxX+\-*()]+", expression):
        return None
    try:
        return int(eval(expression, {"__builtins__": {}}))
    except Exception:
        return None


def parse(text, prefix, skip=()):
    """{value: name} from #define lines and enums whose names start with `prefix` (the first name of a value wins)."""
    text = strip(text)
    known, out = {}, {}
    for name, expression in re.findall(r"^#define\s+(\w+)\s+(.+?)\s*$", text, flags=re.M):
        value = evaluate(expression, known)
        if value is not None:
            known[name] = value
    for body in re.findall(r"enum\s*\w*\s*\{(.*?)\}", text, flags=re.S):
        value = 0
        for member in body.split(","):
            member = member.strip()
            if not member or member.startswith("#"):
                continue
            name, _, explicit = (part.strip() for part in member.partition("="))
            if explicit:
                value = evaluate(explicit, known)
                if value is None:
                    break
            known[name] = value
            value += 1
    for name, value in known.items():
        if name.startswith(prefix) and not any(word in name for word in skip):
            out.setdefault(value, name[len(prefix):])
    return dict(sorted(out.items()))


def table(name, names):
    lines = [f"pub static {name}: &[(u16, &str)] = &["]
    lines += [f'    (0x{value:02X}, "{names[value]}"),' for value in sorted(names)]
    lines.append("];")
    return "\n".join(lines)


def main():
    emerald, firered = Path(sys.argv[1]), Path(sys.argv[2])
    tables = []
    counts = []
    for game, folder in (("EMERALD", emerald), ("FIRERED", firered)):
        read = lambda name: (folder / name).read_text(encoding="utf-8")
        graphics = parse(read("event_objects.h"), "OBJ_EVENT_GFX_", skip=("VARS",))
        graphics = {v: n for v, n in graphics.items() if v < 256 and not n.startswith("NUM")}
        movements = {v: n for v, n in parse(read("event_object_movement.h"), "MOVEMENT_TYPE_").items() if v < 256}
        items = {v: n for v, n in parse(read("items.h"), "ITEM_", skip=("COUNT", "_START", "_END")).items() if v < 0x400}
        items = dict(sorted({0: "NONE", **items}.items()))
        tables += [table(f"{game}_GRAPHICS", graphics), table(f"{game}_MOVEMENTS", movements), table(f"{game}_ITEMS", items)]
        counts.append(f"{game}: {len(graphics)} sprites, {len(movements)} movements, {len(items)} items")
    OUT.write_text(
        "//! The names the decompilations give to the overworld sprites (OBJ_EVENT_GFX_), the\n"
        "//! movement types (MOVEMENT_TYPE_) and the items (ITEM_), sorted by value.\n"
        "//! Generated by tools/gen_event_names.py: don't edit.\n\n" + "\n\n".join(tables) + "\n",
        encoding="utf-8", newline="\n")
    print(f"{OUT}: " + "; ".join(counts))


if __name__ == "__main__":
    main()
